// YYYY-MM-DD in the user's requested Kazakh timezone; stable for the whole day.
export const readingDayKey = (now=new Date()) => {
  const parts=new Intl.DateTimeFormat('en-US',{timeZone:'Asia/Almaty',year:'numeric',month:'2-digit',day:'2-digit'}).formatToParts(now);
  const part=name=>parts.find(item=>item.type===name)?.value;
  return part('year')+'-'+part('month')+'-'+part('day');
};
export const readingPairForDay = (day,theme='all') => {
  const pool=READING_ESSAYS.filter(item=>theme==='all'||item.theme===theme);
  if(pool.length<2)return pool;
  const dayIndex=Math.floor(Date.parse(day+'T00:00:00Z')/86400000);
  if(!Number.isFinite(dayIndex))return pool.slice(0,2);
  // Adjacent daily rotations ensure both essays change each day. The total
  // library rotates over 24 days, each individual theme over four days.
  const first=(((dayIndex*7)%pool.length)+pool.length)%pool.length;
  const second=(first+Math.max(1,Math.floor(pool.length/2)+1))%pool.length;
  return [pool[first],pool[second===first?(first+1)%pool.length:second]];
};
